'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
global.window = {};
require('../accra-map.js');
const M = window.ACCRA_MAP;
assert.ok(M, 'shared Accra map must load');
assert.equal(M.version, 4);
assert.equal(M.expansion, 5);
assert.equal(M.scale, 10);
assert.deepEqual(M.grid, [-4000, -2000, 0, 2000, 4000]);
assert.deepEqual(M.cellCenters, [-3000, -1000, 1000, 3000]);
assert.equal(M.districts.length, 4);
assert.ok(M.districts.every(row => row.length === 4), 'district layout must be 4 x 4');
const names = M.districts.flat();
assert.equal(new Set(names).size, 16, 'all sixteen neighbourhood blocks must be distinct');
assert.deepEqual([...M.roadLines], [...new Set(M.roadLines)].sort((a, b) => a - b), 'road lines must be unique and ordered');
for (const road of M.grid) assert.ok(M.roadLines.includes(road), 'arterial road missing from road line index');
for (const center of M.cellCenters) for (const offset of M.localRoadOffsets) assert.ok(M.roadLines.includes(center + offset), 'local road missing from road line index');
const cell = (x, z) => {
  const i = M.grid.findIndex((v, n) => n < 4 && x >= v && x < M.grid[n + 1]);
  const j = M.grid.findIndex((v, n) => n < 4 && z >= v && z < M.grid[n + 1]);
  return i < 0 || j < 0 ? null : M.districts[i][j];
};
assert.equal(cell(M.places.makola.x, M.places.makola.z), 'Accra Central');
assert.equal(cell(M.places.pub.x, M.places.pub.z), 'Osu');
assert.equal(cell(M.places.mall.x, M.places.mall.z), 'East Legon');
assert.equal(cell(M.places.villa.x, M.places.villa.z), 'East Legon');
assert.equal(cell(M.places.airport.x, M.places.airport.z), 'Airport Residential');
assert.equal(cell(M.places.labadiBeach.x, M.places.labadiBeach.z), 'Labadi');
assert.equal(cell(M.places.estate.x, M.places.estate.z), 'Cantonments');
assert.equal(cell(M.places.stadium.x, M.places.stadium.z), 'Accra Central');
assert.equal(cell(M.places.blackStarSquare.x, M.places.blackStarSquare.z), 'Accra Central');
assert.equal(cell(M.places.nationalTheatre.x, M.places.nationalTheatre.z), 'Osu');
assert.equal(cell(M.places.jamestownLighthouse.x, M.places.jamestownLighthouse.z), 'Jamestown');
assert.equal(cell(M.places.osuCastle.x, M.places.osuCastle.z), 'Osu');
assert.equal(cell(M.places.militaryHospital.x, M.places.militaryHospital.z), 'Airport City');
assert.equal(cell(M.places.achimotaForest.x, M.places.achimotaForest.z), 'Achimota');
assert.equal(cell(M.places.universityOfGhana.x, M.places.universityOfGhana.z), 'East Legon');
const near = (a, b) => Math.hypot(a.x - b.x, a.z - b.z);
assert.ok(near(M.places.stadium, M.places.blackStarSquare) < 400, 'stadium and Black Star Square should be neighbouring civic sites');
assert.ok(near(M.places.nkrumahPark, M.places.blackStarSquare) < 900, 'Nkrumah Park should remain close to Black Star Square');
assert.ok(M.namedRoads.length >= 7, 'named Accra road hierarchy is missing');
for (const name of ['N1 George Bush Highway','Ring Road Central','Liberation Road','Independence Avenue','Spintex Road','Accra–Tema Motorway','Tema Harbour Access Road']) assert.ok(M.namedRoads.some(r => r.name === name), name + ' is missing');
for (const r of M.namedRoads) {
  assert.ok(r.name && r.points.length >= 2 && r.width >= 10, 'named road must have a name, path and usable width');
  assert.ok(r.points.every(p => p.length === 2 && p.every(Number.isFinite)), 'road coordinates must be finite');
}
assert.ok(M.highwayStartZ < M.cityBounds.minZ, 'intercity highway must join north of the city grid');
assert.ok(M.grid.includes(2000), 'airport access must meet the x=2000 city arterial');
const segmentDistance = (p, a, b) => { const dx=b[0]-a[0], dz=b[1]-a[1], t=Math.max(0,Math.min(1,((p.x-a[0])*dx+(p.z-a[1])*dz)/(dx*dx+dz*dz))); return Math.hypot(p.x-(a[0]+t*dx),p.z-(a[1]+t*dz)); };
const n1 = M.namedRoads.find(r => r.name === 'N1 George Bush Highway');
const n1Gap = Math.min(...n1.points.slice(1).map((b,i) => segmentDistance(M.places.airport,n1.points[i],b)));
assert.ok(n1Gap > 1000, 'N1 must pass clear of the Kotoka airport site');
assert.ok(M.coastlineZ > M.cityBounds.maxZ, 'coastline must sit south of the city grid');
const A = M.places.airport;
const westGap = (A.x - 190) - 7;
const eastGap = (2000 - 7) - (A.x + 190);
assert.ok(westGap >= 2 && eastGap >= 2, 'airport fence must not overlap the adjacent arterial roads');
for (const [name, p] of Object.entries(M.places)) {
  if (name === 'atms') continue;
  assert.ok(Number.isFinite(p.x) && Number.isFinite(p.z), name + ' coordinates must be finite');
}
assert.equal(M.places.atms.length, 10, 'ATM destinations must remain available');

const html = fs.readFileSync(path.join(__dirname, '..', 'babylon.html'), 'utf8');
const world = fs.readFileSync(path.join(__dirname, '..', 'accra-world.js'), 'utf8');
const airport = fs.readFileSync(path.join(__dirname, '..', 'accra-airport.js'), 'utf8');
assert.ok(html.includes('window.ACCRA_BUILD = 5'), 'dynamic Accra modules must use the current cache version');
assert.ok(html.includes('accra-map.js?v=5'), 'the expanded shared map must bypass old browser cache');
assert.ok(html.includes('cam.maxZ=12000'), 'camera far clip must include the expanded districts');
assert.ok(world.includes('ground.scaling.set(50, 1, 65)'), 'world terrain must cover the expanded city and highway');
assert.ok(world.includes('ground.position.set(0, 0, -14000)'), 'world terrain must cover the south coast and northern highway');
assert.ok(world.includes('scene.fogStart = 2500; scene.fogEnd = 9500;'), 'expanded districts must remain visible across the wider city');
assert.ok(airport.includes('box(800, .06, 12, C.x + 600, .04, C.z + 56'), 'Kotoka east gate must connect to the x=2000 arterial');
assert.ok(airport.includes('inAccessCorridor'), 'buildings must be cleared from the airport access road corridor');
assert.ok(M.places.temaHarbour.x < 15000 && M.places.temaHarbour.x > 12000, 'Tema Harbour must remain inside the expanded world terrain');
assert.ok(M.namedRoads.find(r => r.name === 'Tema Harbour Access Road').points.at(-1)[0] === M.places.temaHarbour.x, 'Tema Harbour access road must reach the harbour');
console.log('Accra map checks passed: 16 distinct districts, aligned civic landmarks, and named road hierarchy.');
